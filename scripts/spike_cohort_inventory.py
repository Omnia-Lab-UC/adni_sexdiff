#!/usr/bin/env python
"""Spike: the cohort of the adni-cohort proposal, counted under its rules.

Read-only and counts-only. Reads the outputs of ``clean``
(``results/cleaned/``, checked against their manifests' hashes), the visit
columns of the raw metabolomics files, the QT-PAD ADNIMERGE freeze, the
fasting file and the medication table from the data root, applies the rules
the proposal states (the baseline-sample rule, the platform intersection,
the DX.bl stage mapping, the covariates and their sources) and writes one
Markdown report of aggregate counts. No participant identifier is printed or
written.

Usage (inside the Nix shell):
  uv run python -I scripts/spike_cohort_inventory.py --data-root data \
      --cleaned-dir results/cleaned --out openspec/changes/adni-cohort/spike.md
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
from importlib.metadata import version as pkg_version
from pathlib import Path

import pandas as pd

ADNIMERGE = "ADNI_adnimerge_20170629_QT-freeze.csv"
MEDICATION = "ADMCPATIENTDRUGCLASSES_20170512.csv"
FASTING = "BIOMARK.csv"
NMR_RAW = "ADNINIGHTINGALE2.csv"
P180_ADNI2GO_RAW = ("ADMCDUKEP180UPLCADNI2GO.csv", "ADMCDUKEP180FIAADNI2GO.csv")
CLEANED = {"p180": ("P180.csv", "p180_runs.csv"), "nmr": ("NMR.csv",)}

STAGE_MAP = {"CN": "CN", "SMC": "CN", "EMCI": "MCI", "LMCI": "MCI", "AD": "AD"}
STAGES = ["CN", "MCI", "AD"]
DX_ORDER = ["CN", "SMC", "EMCI", "LMCI", "AD"]
SEXES = ["Female", "Male"]
PHASE_MAP = {"ADNI1": "ADNI1", "ADNIGO": "ADNI2GO", "ADNI2": "ADNI2GO"}
PHASES = ["ADNI1", "ADNI2GO"]
STATIN = "HMG CoA reductase inhibitors"
MEDICATION_VISIT = "sc"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def file_row(root: Path, name: str) -> dict:
    path = root / name
    target = os.readlink(path) if path.is_symlink() else "(file)"
    return {"file": f"`{name}`", "target": f"`{target}`", "bytes": path.stat().st_size, "sha256": sha256(path)}


def md_table(rows: list[dict], cols: list[str] | None = None) -> str:
    if not rows:
        return "(none)\n"
    cols = cols or list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out) + "\n"


def crosstab_md(df: pd.DataFrame, row: str, col: str, row_order, col_order) -> str:
    t = pd.crosstab(df[row], df[col]).reindex(index=row_order, columns=col_order, fill_value=0)
    t["all"] = t.sum(axis=1)
    t.loc["all"] = t.sum(axis=0)
    rows = [{row: idx, **{str(c): int(v) for c, v in t.loc[idx].items()}} for idx in t.index]
    return md_table(rows, [row, *map(str, t.columns)])


def visit_sets(df: pd.DataFrame, col: str) -> pd.Series:
    return df.groupby("RID")[col].agg(lambda s: "+".join(sorted(set(s.astype(str)))))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-root", type=Path, default=Path("data"))
    ap.add_argument("--cleaned-dir", type=Path, default=Path("results/cleaned"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    root, cleaned = args.data_root, args.cleaned_dir
    R: list[str] = []

    R.append(f"# Spike: the cohort under the adni-cohort rules ({dt.date.today().isoformat()})\n")
    R.append("Read-only, counts only. Generated by `scripts/spike_cohort_inventory.py` from the outputs of `clean` "
             "and the data root (pandas " + pkg_version("pandas") + "). Every number below is a count, a proportion, "
             "a summary statistic or a hash. No participant identifier appears in this file.\n")

    # ---- inputs -------------------------------------------------------------
    R.append("## Files read\n")
    R.append("Data root (hashes through the symlinks):\n")
    R.append(md_table([file_row(root, n) for n in (ADNIMERGE, MEDICATION, FASTING, NMR_RAW, *P180_ADNI2GO_RAW)]))
    rows = []
    for platform, names in CLEANED.items():
        manifest = json.loads((cleaned / platform / "clean_manifest.json").read_text())
        for name in names:
            observed = sha256(cleaned / platform / name)
            rows.append({"file": f"`{platform}/{name}`", "sha256": observed[:16] + "…",
                         "equals clean_manifest.json": observed == manifest["outputs"][name]["sha256"]})
    R.append("Outputs of `clean` (participant-level, read in place), against their manifests:\n")
    R.append(md_table(rows))

    # ---- cleaned participants and their sample visits ------------------------
    p180 = pd.read_csv(cleaned / "p180" / "P180.csv", usecols=["RID"])
    nmr = pd.read_csv(cleaned / "nmr" / "NMR.csv", usecols=["RID"])
    runs = pd.read_csv(cleaned / "p180" / "p180_runs.csv").set_index("RID")["run"]
    p180_ids, nmr_ids = set(p180.RID), set(nmr.RID)

    R.append("## Visit of each platform's sample\n")
    adni2go = pd.concat([pd.read_csv(root / f, usecols=["RID", "VISCODE"]) for f in P180_ADNI2GO_RAW])
    adni2go = adni2go[adni2go.RID.isin(set(runs[runs == "ADNI2GO"].index))]
    p180_sets = visit_sets(adni2go, "VISCODE")
    nmr_raw = pd.read_csv(root / NMR_RAW, usecols=["RID", "VISCODE2"])
    nmr_sets = visit_sets(nmr_raw[nmr_raw.RID.isin(nmr_ids)], "VISCODE2")
    R.append("Participants of the cleaned tables by the set of visit codes of their raw records "
             "(ADNI-1 p180 files carry no visit column; the rule takes them as baseline):\n")
    R.append(md_table(
        [{"platform": "p180 ADNI-1 run", "visit set": "(no visit column)", "participants": int((runs == "ADNI1").sum())}]
        + [{"platform": "p180 ADNI-GO/2 run", "visit set": k, "participants": int(v)} for k, v in p180_sets.value_counts().items()]
        + [{"platform": "nmr", "visit set": k, "participants": int(v)} for k, v in nmr_sets.value_counts().items()]))
    p180_bl = {rid for rid in p180_ids if runs[rid] == "ADNI1" or p180_sets.get(rid) == "bl"}
    nmr_bl = set(nmr_sets[nmr_sets == "bl"].index)
    not_bl = nmr_ids - nmr_bl
    fast = pd.read_csv(root / FASTING, usecols=["RID", "VISCODE2", "BIFAST"])
    fast_nb = fast[fast.RID.isin(not_bl)]
    at_sample = fast_nb[[v in nmr_sets[rid].split("+") for rid, v in zip(fast_nb.RID, fast_nb.VISCODE2)]]
    R.append(f"Cleaned NMR participants whose NMR sample is not from `bl`: {len(not_bl)}. Of them, with `BIFAST` = 1 "
             f"on a `{FASTING}` `bl` row (what metabo_adni's fasting filter reads): "
             f"{fast_nb[(fast_nb.VISCODE2 == 'bl') & (fast_nb.BIFAST == 1)].RID.nunique()}; with any `{FASTING}` row "
             f"at their sample's visit: {at_sample.RID.nunique()}.\n")

    # ---- clinical table ------------------------------------------------------
    m = pd.read_csv(root / ADNIMERGE, low_memory=False,
                    usecols=["RID", "VISCODE", "ORIGPROT", "DX.bl", "DX", "AGE", "PTGENDER", "PTEDUCAT", "APOE4"])
    bl = m[m.VISCODE == "bl"]
    R.append("## ADNIMERGE baseline rows\n")
    R.append(f"Rows {len(m)}; `bl` rows {len(bl)}; unique RIDs among them {bl.RID.nunique()}. "
             f"`DX.bl` values {sorted(bl['DX.bl'].dropna().unique())}; `PTGENDER` values "
             f"{sorted(bl.PTGENDER.dropna().unique())}; `ORIGPROT` values {sorted(bl.ORIGPROT.dropna().unique())}; "
             f"`APOE4` values {sorted(bl.APOE4.dropna().unique())}.\n")
    bl = bl.set_index("RID")

    meds = pd.read_csv(root / MEDICATION, dtype=str, low_memory=False)
    sc = meds[meds.VISCODE2 == MEDICATION_VISIT].copy()
    sc["RID"] = sc.RID.astype(int)
    R.append("## Medication table\n")
    R.append(f"`{MEDICATION_VISIT}` rows {len(sc)}, unique RIDs {sc.RID.nunique()}; column `{STATIN}` present: "
             f"{STATIN in meds.columns}; filled `{STATIN}` cells at `{MEDICATION_VISIT}`: {int(sc[STATIN].notna().sum())}. "
             "A filled cell is use; an empty cell on an existing row is no use; no row is missing.\n")
    statin = sc.drop_duplicates("RID").set_index("RID")[STATIN].notna().astype(int)

    # ---- cohort table under the rules ---------------------------------------
    ids = sorted(p180_ids | nmr_ids)
    c = pd.DataFrame(index=pd.Index(ids, name="RID"))
    c["in_p180"] = c.index.isin(p180_ids)
    c["in_nmr"] = c.index.isin(nmr_ids)
    c["p180_bl"] = c.index.isin(p180_bl)
    c["nmr_bl"] = c.index.isin(nmr_bl)
    c = c.join(bl[["ORIGPROT", "DX.bl", "DX", "AGE", "PTGENDER", "PTEDUCAT", "APOE4"]], how="left")
    c["has_bl_row"] = c["DX.bl"].notna() | c.PTGENDER.notna()
    c["stage"] = c["DX.bl"].map(STAGE_MAP)
    c["phase"] = c.ORIGPROT.map(PHASE_MAP)
    c["statin"] = statin.reindex(c.index)
    c["run"] = runs.reindex(c.index)
    covars = {"age": "AGE", "education": "PTEDUCAT", "apoe4": "APOE4", "phase": "phase", "statin": "statin"}

    R.append("## Cohort cascade\n")
    rows, final = [], {}
    for label, in_col, bl_col in (("p180", "in_p180", "p180_bl"), ("nmr", "in_nmr", "nmr_bl")):
        s = c[c[in_col]]
        rows.append({"set": label, "step": "cleaned", "participants": len(s)})
        for name, keep in (("sample at `bl`", lambda f: f[bl_col]),
                           ("ADNIMERGE `bl` row", lambda f: f.has_bl_row),
                           ("`DX.bl` in the stage map", lambda f: f.stage.notna()),
                           ("sex Female/Male", lambda f: f.PTGENDER.isin(SEXES)),
                           ("covariates complete", lambda f: f[list(covars.values())].notna().all(axis=1))):
            s = s[keep(s)]
            rows.append({"set": label, "step": name, "participants": len(s)})
        final[label] = s
    both_ids = set(final["p180"].index) & set(final["nmr"].index)
    final["intersection"] = c.loc[sorted(both_ids)]
    rows.append({"set": "intersection", "step": "both platform sets", "participants": len(final["intersection"])})
    R.append(md_table(rows))
    lost = (c.in_p180 & c.in_nmr).sum() - len(final["intersection"])
    R.append(f"Cleaned on both platforms: {int((c.in_p180 & c.in_nmr).sum())}; intersection cohort: "
             f"{len(final['intersection'])} ({lost} excluded by the rules).\n")

    R.append("## Sex × stage\n")
    for label, s in final.items():
        R.append(f"{label} (n = {len(s)}):\n")
        R.append(crosstab_md(s, "PTGENDER", "stage", SEXES, STAGES))

    i = final["intersection"]
    R.append("## Stage source: `DX.bl` against `DX` on the `bl` row (intersection)\n")
    t = pd.crosstab(i["DX.bl"], i.DX.fillna("(missing)")).reindex(index=DX_ORDER, fill_value=0)
    R.append(md_table([{"DX.bl": k, **{str(col): int(v) for col, v in t.loc[k].items()}} for k in t.index],
                      ["DX.bl", *map(str, t.columns)]))
    # "X to Y" is a change recorded at the visit; the diagnosis at the visit is Y.
    current = i.DX.dropna().str.split(" to ").str[-1].map({"NL": "CN", "MCI": "MCI", "Dementia": "AD"})
    R.append(f"Reading `DX` as the diagnosis at the visit (`NL` → CN, `MCI` → MCI, `Dementia` → AD; a change "
             f"\"X to Y\" → Y): agrees with the mapped stage for {int((current == i.stage[current.index]).sum())}, "
             f"differs for {int((current != i.stage[current.index]).sum())}, `DX` missing for {int(i.DX.isna().sum())}.\n")

    R.append("## Composition: sex × DX.bl × phase (intersection)\n")
    for sex in SEXES:
        R.append(f"{sex}:\n")
        R.append(crosstab_md(i[i.PTGENDER == sex], "DX.bl", "phase", DX_ORDER, PHASES))
    rows = []
    for sex in SEXES:
        for phase in PHASES:
            s = i[(i.PTGENDER == sex) & (i.phase == phase)]
            mci, cn = s[s.stage == "MCI"], s[s.stage == "CN"]
            rows.append({"sex": sex, "phase": phase,
                         "EMCI share of MCI": f"{(mci['DX.bl'] == 'EMCI').mean():.2f}" if len(mci) else "–",
                         "SMC share of CN": f"{(cn['DX.bl'] == 'SMC').mean():.2f}" if len(cn) else "–"})
    for sex in SEXES:
        s = i[i.PTGENDER == sex]
        mci, cn = s[s.stage == "MCI"], s[s.stage == "CN"]
        rows.append({"sex": sex, "phase": "both", "EMCI share of MCI": f"{(mci['DX.bl'] == 'EMCI').mean():.2f}",
                     "SMC share of CN": f"{(cn['DX.bl'] == 'SMC').mean():.2f}"})
    R.append(md_table(rows))
    core = i[i["DX.bl"].isin(["CN", "LMCI", "AD"])]
    R.append(f"Sensitivity-arm set (CN, LMCI, AD only; not part of this change): n = {len(core)}.\n")
    R.append(crosstab_md(core, "PTGENDER", "stage", SEXES, STAGES))

    R.append("## Phase against the p180 run (intersection)\n")
    R.append(crosstab_md(i, "phase", "run", PHASES, PHASES))
    R.append(f"Disagreements: {int((i.phase != i.run).sum())}.\n")

    R.append("## Covariates by sex × stage (intersection)\n")
    rows = []
    for sex in SEXES:
        for stage in STAGES:
            s = i[(i.PTGENDER == sex) & (i.stage == stage)]
            rows.append({"sex": sex, "stage": stage, "n": len(s),
                         "age mean (sd)": f"{s.AGE.mean():.1f} ({s.AGE.std():.1f})",
                         "education mean (sd)": f"{s.PTEDUCAT.mean():.1f} ({s.PTEDUCAT.std():.1f})",
                         "APOE4 0/1/2": "/".join(str(int((s.APOE4 == k).sum())) for k in (0, 1, 2)),
                         "phase ADNI1/ADNI2GO": "/".join(str(int((s.phase == p).sum())) for p in PHASES),
                         "statin users": int(s.statin.sum())})
    R.append(md_table(rows))
    R.append(f"Ranges: age {i.AGE.min():.1f}–{i.AGE.max():.1f}; education {int(i.PTEDUCAT.min())}–{int(i.PTEDUCAT.max())} "
             f"years. Missing values among the five covariates in the intersection: "
             f"{int(i[list(covars.values())].isna().sum().sum())}.\n")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(R), encoding="utf-8")
    print(f"[spike] wrote {args.out} ({len(R)} blocks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
