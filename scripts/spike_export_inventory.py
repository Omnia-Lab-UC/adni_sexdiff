#!/usr/bin/env python
"""Spike: the MOTCO blocks of the adni-export proposal, summarised under its rule.

Read-only and aggregate-only. Reads the outputs of ``clean`` and ``cohort``
(checked against their manifests' hashes) and, for one cross-check only, the
Nightingale data dictionary in the data root. It restricts the cleaned
matrices to the analysis cohort, applies the feature rule the proposal
states (block membership by family, the per-metabolite floor and the log2
scale) and writes one Markdown report of counts and summary statistics per
block or per family. No participant identifier or participant value is
printed or written.

Usage (inside the Nix shell):
  uv run python -I scripts/spike_export_inventory.py --data-root data \
      --cleaned-dir results/cleaned --cohort-dir results/cohort \
      --out openspec/changes/<change>/spike.md
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import hashlib
import json
from importlib.metadata import version as pkg_version
from pathlib import Path

import numpy as np
import pandas as pd

CLEAN_TABLES = {"p180": "P180.csv", "nmr": "NMR.csv"}
COHORT_TABLE = "cohort.csv"
NMR_DICTIONARY = "Metabolomics/NMR/ADNINIGHTINGALE2_DICT_11Jul2024.csv"
CONCENTRATION_UNITS = ("mmol/l", "µmol/l", "g/l")
SEXES = ["Female", "Male"]
STAGES = ["CN", "MCI", "AD"]
PHASES = ["ADNI1", "ADNI2GO"]
FLOOR_QUANTILE = 0.05

# The NMR families of the rule. A column is derived when its name carries one
# of these marks; every other column is a concentration and enters the block.
NMR_DERIVED = {
    "percentage": lambda c: c.endswith("_PCT"),
    "ratio": lambda c: "_BY_" in c,
    "degree": lambda c: c == "UNSATURATION",
    "size": lambda c: c.endswith("_SIZE"),
}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def md_table(rows: list[dict], cols: list[str] | None = None) -> str:
    if not rows:
        return "(none)\n"
    cols = cols or list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out) + "\n"


def family_of(column: str) -> str:
    for name, test in NMR_DERIVED.items():
        if test(column):
            return name
    if column.split("_")[0] in ("XXL", "XL", "L", "M", "S", "XS", "IDL"):
        return "subclass concentration"
    return "concentration"


def shape_counts(M: np.ndarray) -> dict:
    """Per-feature skew and leverage, counted over features. Aggregate only."""
    df = pd.DataFrame(M)
    s = df.skew().to_numpy()
    z = ((df - df.mean()) / df.std(ddof=0)).abs().max().to_numpy()
    return {"abs skew > 1": int((np.abs(s) > 1).sum()), "skew < -1": int((s < -1).sum()),
            "median abs skew": f"{np.median(np.abs(s)):.2f}",
            "max abs z > 5": int((z > 5).sum()), "max abs z > 8": int((z > 8).sum()),
            "max abs z > 15": int((z > 15).sum())}


def spectrum(M: np.ndarray) -> dict:
    Z = (M - M.mean(0)) / M.std(0)
    s = np.linalg.svd(Z, compute_uv=False)
    ev = s**2 / (s**2).sum()
    return {"features": M.shape[1], "PC1 share": f"{ev[0]:.3f}", "PC1-3 share": f"{ev[:3].sum():.3f}",
            "PC1-10 share": f"{ev[:10].sum():.3f}", "effective rank": f"{1 / np.sum(ev**2):.1f}",
            "numerical rank (1e-8)": int((s / s[0] > 1e-8).sum())}


def phase_offset(M: np.ndarray, phase: np.ndarray) -> dict:
    a, b = M[phase == PHASES[0]], M[phase == PHASES[1]]
    d = (a.mean(0) - b.mean(0)) / np.sqrt((a.var(0) + b.var(0)) / 2)
    Z = (M - M.mean(0)) / M.std(0)
    u, _, _ = np.linalg.svd(Z, full_matrices=False)
    g = (phase == PHASES[0]).astype(float)
    return {"median abs d": f"{np.median(np.abs(d)):.2f}", "max abs d": f"{np.abs(d).max():.2f}",
            "abs d > 0.5": int((np.abs(d) > 0.5).sum()), "abs d > 1": int((np.abs(d) > 1).sum()),
            "abs corr(PC1, phase)": f"{abs(np.corrcoef(u[:, 0], g)[0, 1]):.2f}",
            "abs corr(PC2, phase)": f"{abs(np.corrcoef(u[:, 1], g)[0, 1]):.2f}"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-root", type=Path, default=Path("data"))
    ap.add_argument("--cleaned-dir", type=Path, default=Path("results/cleaned"))
    ap.add_argument("--cohort-dir", type=Path, default=Path("results/cohort"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    cleaned, cohort_dir = args.cleaned_dir, args.cohort_dir
    R: list[str] = []

    R.append(f"# Spike: the MOTCO blocks under the adni-export rule ({dt.date.today().isoformat()})\n")
    R.append("Read-only, aggregate only. Generated by `scripts/spike_export_inventory.py` from the outputs of "
             "`clean` and `cohort` (pandas " + pkg_version("pandas") + ", numpy " + pkg_version("numpy") +
             "). Every number below is a count, a share, a summary statistic over participants of one "
             "metabolite, a summary over metabolites, or a hash. No participant identifier or participant "
             "value appears in this file.\n")

    # ---- inputs -------------------------------------------------------------
    R.append("## Files read\n")
    rows = []
    clean_manifests = {}
    for platform, name in CLEAN_TABLES.items():
        manifest = json.loads((cleaned / platform / "clean_manifest.json").read_text())
        clean_manifests[platform] = manifest
        observed = sha256(cleaned / platform / name)
        rows.append({"file": f"`{platform}/{name}`", "sha256": observed[:16] + "…",
                     "equals its manifest": observed == manifest["outputs"][name]["sha256"]})
    cohort_manifest = json.loads((cohort_dir / "cohort_manifest.json").read_text())
    observed = sha256(cohort_dir / COHORT_TABLE)
    rows.append({"file": f"`cohort/{COHORT_TABLE}`", "sha256": observed[:16] + "…",
                 "equals its manifest": observed == cohort_manifest["outputs"][COHORT_TABLE]["sha256"]})
    R.append("Outputs of `clean` and `cohort` (participant-level, read in place), against their manifests:\n")
    R.append(md_table(rows))
    chain = all(
        cohort_manifest["inputs"]["clean"][p]["outputs"][n]["sha256"] == clean_manifests[p]["outputs"][n]["sha256"]
        for p, n in CLEAN_TABLES.items()
    ) if "clean" in cohort_manifest.get("inputs", {}) else None
    R.append(f"The cohort manifest's recorded clean hashes equal the clean manifests' output hashes: {chain}.\n")

    # ---- cohort rows ---------------------------------------------------------
    cohort = pd.read_csv(cohort_dir / COHORT_TABLE)
    both = cohort[cohort.p180.astype(bool) & cohort.nmr.astype(bool)].reset_index(drop=True)
    R.append("## Exported participants\n")
    R.append(f"Rows of `cohort.csv`: {len(cohort)}; with both platform flags (the export): {len(both)}; "
             f"`rid` strictly increasing in file order: {bool(both.rid.is_monotonic_increasing and both.rid.is_unique)}.\n")
    t = pd.crosstab(both.sex, both.stage).reindex(index=SEXES, columns=STAGES, fill_value=0)
    t["all"] = t.sum(axis=1)
    t.loc["all"] = t.sum(axis=0)
    R.append(md_table([{"sex": idx, **{str(c): int(v) for c, v in t.loc[idx].items()}} for idx in t.index],
                      ["sex", *map(str, t.columns)]))
    covars = ["age", "education", "apoe4", "phase", "statin"]
    R.append(f"Covariate columns present: {all(c in both.columns for c in covars)}; missing values among them: "
             f"{int(both[covars].isna().sum().sum())}; `phase` values {sorted(both.phase.unique())}.\n")

    # ---- blocks restricted to the cohort --------------------------------------
    blocks: dict[str, pd.DataFrame] = {}
    for platform, name in CLEAN_TABLES.items():
        table = pd.read_csv(cleaned / platform / name, index_col="RID")
        missing = set(both.rid) - set(table.index)
        if missing:
            raise SystemExit(f"{platform}: {len(missing)} cohort participants absent from {name}")
        blocks[platform] = table.loc[both.rid.to_numpy()]
    R.append("## Block membership\n")
    nmr_cols = list(blocks["nmr"].columns)
    families = pd.Series({c: family_of(c) for c in nmr_cols})
    kept_nmr = [c for c in nmr_cols if families[c] not in NMR_DERIVED]
    rows = [{"platform": "p180", "family": "concentration (µM)", "status": "kept", "metabolites": blocks["p180"].shape[1]}]
    for fam in ("concentration", "subclass concentration", *NMR_DERIVED):
        rows.append({"platform": "nmr", "family": fam, "status": "derived" if fam in NMR_DERIVED else "kept",
                     "metabolites": int((families == fam).sum())})
    R.append(md_table(rows))
    R.append(f"p180: {blocks['p180'].shape[1]} cleaned metabolites, all kept. NMR: {len(nmr_cols)} cleaned columns, "
             f"{len(kept_nmr)} kept, {len(nmr_cols) - len(kept_nmr)} derived.\n")

    # cross-check of the name rule against the Nightingale dictionary's units
    dictionary = {r["FLDNAME"]: r["UNITS"] for r in csv.DictReader(
        open(args.data_root / NMR_DICTIONARY, encoding="latin-1", newline=""))}
    units = pd.Series({c: dictionary.get(c, "(absent)").replace("?mol/l", "µmol/l") for c in nmr_cols})
    by_unit = pd.crosstab(units, families.map(lambda f: "derived" if f in NMR_DERIVED else "kept"))
    R.append("Units of the 245 cleaned NMR columns in the Nightingale dictionary "
             f"(`{NMR_DICTIONARY}`), against the name rule:\n")
    R.append(md_table([{"unit": u, **{str(c): int(v) for c, v in by_unit.loc[u].items()}} for u in by_unit.index],
                      ["unit", *map(str, by_unit.columns)]))
    agree = all((units[c] in CONCENTRATION_UNITS) == (c in kept_nmr) for c in nmr_cols)
    R.append(f"Every kept column has a concentration unit and every derived column does not: {agree}. "
             f"Column in µmol/l: {[c for c in nmr_cols if units[c] == 'µmol/l']}.\n")

    exported = {"p180": blocks["p180"], "nmr": blocks["nmr"][kept_nmr]}

    # ---- values and the floor ---------------------------------------------------
    R.append("## Values in the exported cohort and the floor\n")
    rows, floors = [], {}
    for platform, table in exported.items():
        X = table.to_numpy(float)
        med = np.median(X, axis=0)
        floor = np.quantile(X, FLOOR_QUANTILE, axis=0)
        floors[platform] = floor
        zeros = (X == 0).sum(axis=0)
        ratio = floor / med
        rows.append({"block": platform, "participants × metabolites": f"{X.shape[0]} × {X.shape[1]}",
                     "missing": int(np.isnan(X).sum()), "negative": int((X < 0).sum()),
                     "zero cells": int(zeros.sum()), "metabolites with zeros": int((zeros > 0).sum()),
                     "median < 1": int((med < 1).sum()), "median < 0.01": int((med < 0.01).sum()),
                     "floor ≤ 0": int((floor <= 0).sum()),
                     "floor / median: median": f"{np.median(ratio):.2f}",
                     "floor / median: min": f"{ratio.min():.3f}", "floor / median: max": f"{ratio.max():.2f}"})
    R.append(f"The floor of a metabolite is its {FLOOR_QUANTILE:.0%} quantile over the exported participants "
             "(linear interpolation, numpy's default). Zero and negative cells are counted before it is added.\n")
    R.append(md_table(rows))
    zero_cols = [(c, int(z)) for c, z in zip(exported["nmr"].columns, (exported["nmr"].to_numpy(float) == 0).sum(0)) if z]
    R.append("NMR metabolites with zero cells (metabolite, zero cells, floor / median): " + ", ".join(
        f"`{c}` {z} {floors['nmr'][list(exported['nmr'].columns).index(c)] / np.median(exported['nmr'][c]):.2f}"
        for c, z in zero_cols) + ".\n")

    # ---- distribution shape under candidate scales -----------------------------
    R.append("## Distribution shape under candidate scales\n")
    R.append("Per metabolite, over the exported participants: skew (pandas, bias-corrected) and the largest "
             "absolute z-score. Counted over metabolites. `log2(x + floor)` is the rule.\n")
    for platform, table in exported.items():
        X = table.to_numpy(float)
        minpos = np.array([c[c > 0].min() for c in X.T])
        candidates = {"raw": X, "log2(x + 1)": np.log2(X + 1), "log2(x + min/2)": np.log2(X + minpos / 2),
                      "log2(x + floor)": np.log2(X + floors[platform]),
                      "glog, c = floor": np.log2(X + np.sqrt(X**2 + floors[platform] ** 2))}
        R.append(f"{platform} ({X.shape[1]} metabolites):\n")
        R.append(md_table([{"scale": k, **shape_counts(M)} for k, M in candidates.items()]))
    X = blocks["nmr"].to_numpy(float)
    fl = np.quantile(X, FLOOR_QUANTILE, axis=0)
    R.append("For reference, all 245 NMR columns (the derived ones included) under the rule's scale, and the "
             "derived columns alone on their own scale:\n")
    derived_cols = [c for c in nmr_cols if c not in kept_nmr]
    R.append(md_table([{"columns": "all 245, log2(x + floor)", **shape_counts(np.log2(X + fl))},
                       {"columns": f"{len(derived_cols)} derived, raw", **shape_counts(blocks["nmr"][derived_cols].to_numpy(float))}]))
    transformed = {p: np.log2(t.to_numpy(float) + floors[p]) for p, t in exported.items()}
    R.append("Non-finite cells after the rule's transform: " +
             ", ".join(f"{p} {int((~np.isfinite(M)).sum())}" for p, M in transformed.items()) + ".\n")

    # ---- block structure --------------------------------------------------------
    R.append("## Block structure after pooled standardization\n")
    R.append("MOTCO z-scores every feature and concatenates the blocks unweighted, so each feature carries one "
             "unit of variance and a block's share of the joint matrix is its feature count.\n")
    rows = [{"block": f"{p}, log2(x + floor)", **spectrum(M)} for p, M in transformed.items()]
    rows.append({"block": "nmr, all 245, log2(x + floor)", **spectrum(np.log2(X + fl))})
    R.append(md_table(rows))
    n_p, n_n = transformed["p180"].shape[1], transformed["nmr"].shape[1]
    R.append(md_table([
        {"joint matrix": f"p180 {n_p} + nmr {n_n} (the rule)", "p180 share": f"{n_p / (n_p + n_n):.3f}", "nmr share": f"{n_n / (n_p + n_n):.3f}"},
        {"joint matrix": f"p180 {n_p} + nmr 245 (all cleaned columns)", "p180 share": f"{n_p / (n_p + 245):.3f}", "nmr share": f"{245 / (n_p + 245):.3f}"}]))

    # ---- phase offset -----------------------------------------------------------
    R.append("## Phase offset per block\n")
    R.append("Standardized mean difference `d` of every metabolite between `phase` ADNI1 and ADNI2GO participants, "
             "on the rule's scale, and the correlation of the block's first principal components with phase. "
             "The same participants on both blocks: the p180 run equals the phase, the NMR assay was one batch.\n")
    phase = both.phase.to_numpy()
    R.append(md_table([{"block": p, **phase_offset(M, phase)} for p, M in transformed.items()]))
    t = pd.crosstab(both.phase, both.dx_bl).reindex(index=PHASES, fill_value=0)
    R.append("Stage composition by phase among the exported participants (`dx_bl`):\n")
    R.append(md_table([{"phase": ph, **{str(c): int(v) for c, v in t.loc[ph].items()}} for ph in t.index],
                      ["phase", *map(str, t.columns)]))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(R), encoding="utf-8")
    print(f"[spike] wrote {args.out} ({len(R)} blocks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
